#include <iostream>
using namespace std;

// ============================================================
// 一、函数的定义与声明
// ============================================================
// 老师傅比喻：函数就像一台加工机器，你给它原材料（参数），
// 它加工完给你成品（返回值）。把重复的工作封装成函数，
// 就像把生产线标准化，用的时候调用一下就行。

// 函数声明（也叫函数原型）：告诉编译器有这么个函数，具体实现可以在后面
// 格式：返回值类型 函数名(参数类型列表);
int add(int a, int b);          // 两个整数相加
void printHello();              // 没有返回值用 void
double calculateArea(double);   // 参数名可以省略（但不推荐省略，不清晰）

// 函数定义：函数的具体实现
// 老师傅的话：函数名要"见名知意"，一看就知道这个函数干嘛的
int add(int a, int b)
{
    return a + b;  // return 把结果返回给调用者，同时结束函数
}

void printHello()
{
    cout << "Hello, 函数！" << endl;
    // void函数不需要return，或者写 return; 不带值
}

double calculateArea(double radius)
{
    const double PI = 3.1415926;
    return PI * radius * radius;
}

// ============================================================
// 二、参数传递的三种方式
// ============================================================

// 2.1 值传递：传的是"副本"，函数里改的是副本，不影响原来的变量
// 老师傅比喻：就像给你一份复印件，你在复印件上乱画，原件不受影响
void swapByValue(int x, int y)
{
    int temp = x;
    x = y;
    y = temp;
    cout << "  函数内部：x = " << x << ", y = " << y << endl;
}

// 2.2 引用传递：传的是"别名"，函数里改的就是原来的变量
// 老师傅比喻：就像给你一把钥匙，你直接打开原来的箱子改东西
void swapByRef(int &x, int &y)
{
    int temp = x;
    x = y;
    y = temp;
}

// 2.3 指针传递：传的是"地址"，通过地址找到原变量来修改
// 老师傅比喻：就像告诉你箱子的位置，你自己找过去改东西
void swapByPtr(int *x, int *y)
{
    int temp = *x;  // *x 表示"取x地址处的值"
    *x = *y;
    *y = temp;
}

// ============================================================
// 三、函数重载
// ============================================================
// 老师傅说：函数名可以一样，只要参数不一样就行，编译器能分清
// 就像同名的人，一个高一个矮，你不会叫错人
// 注意：重载只看参数列表，和返回值没关系！

int maxNum(int a, int b)            // 两个int
{
    return (a > b) ? a : b;
}

double maxNum(double a, double b)   // 两个double
{
    return (a > b) ? a : b;
}

int maxNum(int a, int b, int c)     // 三个int
{
    return maxNum(maxNum(a, b), c);
}

// ============================================================
// 四、默认参数
// ============================================================
// 老师傅说：有些参数大多数时候用某个固定值，就可以设成默认值
// 调用时不写就用默认值，写了就用你给的值
// 注意：默认参数必须从右往左写，不能中间有默认参数左边没有

void printMessage(string msg, int times = 1)
{
    for (int i = 0; i < times; i++) {
        cout << "  " << msg << endl;
    }
}

// ============================================================
// 五、递归
// ============================================================
// 老师傅比喻：递归就是"自己调用自己"，就像两面镜子对着照，无限反射
// 但递归必须有"终止条件"，否则就无限循环把栈撑爆了

// 5.1 阶乘：n! = n * (n-1)!，0! = 1
int factorial(int n)
{
    if (n <= 1) {
        return 1;  // 终止条件（基准情况）
    }
    return n * factorial(n - 1);  // 递归调用
}

// 5.2 斐波那契数列：F(n) = F(n-1) + F(n-2)，F(0)=0, F(1)=1
// 老师傅提醒：这个递归写法会有大量重复计算，效率很低，只是用来演示递归
// 实际用循环或者动态规划更好
int fibonacci(int n)
{
    if (n == 0) return 0;
    if (n == 1) return 1;
    return fibonacci(n - 1) + fibonacci(n - 2);
}

// ============================================================
// 六、函数指针入门
// ============================================================
// 老师傅说：函数也有地址，函数指针就是指向函数的指针
// 就像普通指针存变量地址一样，函数指针存函数的地址
// 格式：返回值类型 (*指针名)(参数类型列表)

// 定义一个函数指针类型，方便使用
typedef int (*MathFunc)(int, int);
// C++11之后也可以用 using：
// using MathFunc = int(*)(int, int);

// 一个使用函数指针的函数
int calculate(int a, int b, MathFunc func)
{
    return func(a, b);
}

// ============================================================
// 七、作用域与生命周期
// ============================================================
// 老师傅说：变量不是到处都能用的，它有"活动范围"（作用域）
// 和"存活时间"（生命周期），就像人有活动范围和寿命一样

int globalVar = 100;  // 全局变量：整个程序都能访问，程序启动就存在

void testScope()
{
    int localVar = 10;  // 局部变量：只在函数内有效，函数结束就销毁
    static int staticVar = 0;  // 静态局部变量：函数结束也不销毁，只初始化一次

    staticVar++;
    cout << "  局部变量 localVar = " << localVar << endl;
    cout << "  静态变量 staticVar = " << staticVar << "（每次调用加1）" << endl;
    cout << "  全局变量 globalVar = " << globalVar << endl;
}

// ============================================================
// 主函数
// ============================================================
int main()
{
    cout << "===== 1. 函数的定义与声明 =====" << endl;
    printHello();
    cout << "3 + 5 = " << add(3, 5) << endl;
    cout << "半径为5的圆面积 = " << calculateArea(5.0) << endl;
    cout << endl;

    // ---- 参数传递 ----
    cout << "===== 2. 参数传递的三种方式 =====" << endl;

    int a = 10, b = 20;
    cout << "--- 值传递 ---" << endl;
    cout << "交换前：a = " << a << ", b = " << b << endl;
    swapByValue(a, b);
    cout << "交换后：a = " << a << ", b = " << b << "（值传递，原值不变！）" << endl;

    cout << "--- 引用传递 ---" << endl;
    cout << "交换前：a = " << a << ", b = " << b << endl;
    swapByRef(a, b);
    cout << "交换后：a = " << a << ", b = " << b << "（引用传递，原值改变！）" << endl;

    cout << "--- 指针传递 ---" << endl;
    cout << "交换前：a = " << a << ", b = " << b << endl;
    swapByPtr(&a, &b);  // &a 取a的地址
    cout << "交换后：a = " << a << ", b = " << b << "（指针传递，原值改变！）" << endl;
    cout << endl;

    // ---- 函数重载 ----
    cout << "===== 3. 函数重载 =====" << endl;
    cout << "maxNum(3, 7) = " << maxNum(3, 7) << "（两个int版本）" << endl;
    cout << "maxNum(3.5, 2.8) = " << maxNum(3.5, 2.8) << "（两个double版本）" << endl;
    cout << "maxNum(3, 7, 5) = " << maxNum(3, 7, 5) << "（三个int版本）" << endl;
    cout << endl;

    // ---- 默认参数 ----
    cout << "===== 4. 默认参数 =====" << endl;
    cout << "只传一个参数（默认打印1次）：" << endl;
    printMessage("你好，C++！");
    cout << "传两个参数（指定打印3次）：" << endl;
    printMessage("重要的事情说三遍！", 3);
    cout << endl;

    // ---- 递归 ----
    cout << "===== 5. 递归 =====" << endl;
    cout << "--- 阶乘 ---" << endl;
    for (int i = 0; i <= 6; i++) {
        cout << i << "! = " << factorial(i) << endl;
    }

    cout << "--- 斐波那契数列前10项 ---" << endl;
    for (int i = 0; i < 10; i++) {
        cout << fibonacci(i) << " ";
    }
    cout << endl;
    cout << endl;

    // ---- 函数指针 ----
    cout << "===== 6. 函数指针入门 =====" << endl;

    // 定义一个函数指针，指向add函数
    MathFunc myFunc = add;
    cout << "通过函数指针调用add(5, 3) = " << myFunc(5, 3) << endl;

    // 函数指针作为参数传入（回调函数的雏形）
    cout << "calculate(10, 4, add) = " << calculate(10, 4, add) << endl;

    // 也可以传其他符合签名的函数，比如 maxNum(int,int)
    cout << "calculate(10, 4, maxNum) = " << calculate(10, 4, maxNum) << endl;
    cout << endl;

    // ---- 作用域与生命周期 ----
    cout << "===== 7. 作用域与生命周期 =====" << endl;
    cout << "第一次调用 testScope()：" << endl;
    testScope();
    cout << "第二次调用 testScope()：" << endl;
    testScope();
    cout << "第三次调用 testScope()：" << endl;
    testScope();
    cout << "注意看静态变量 staticVar，它记住了上次的值！" << endl;
    cout << endl;

    // ============================================================
    // 老师傅的话：为什么推荐引用传递而不是指针传递
    // ============================================================
    cout << "========================================" << endl;
    cout << "  老师傅的话" << endl;
    cout << "========================================" << endl;
    cout << "  引用传递 vs 指针传递，该选哪个？" << endl;
    cout << endl;
    cout << "  1. 引用更安全：引用必须初始化，不能是“空”的" << endl;
    cout << "     指针可以是nullptr，一不小心就空指针崩溃" << endl;
    cout << endl;
    cout << "  2. 引用更直观：调用时不用写&，就像普通传参" << endl;
    cout << "     指针要传地址，调用时要写&，函数里要写*，容易搞混" << endl;
    cout << endl;
    cout << "  3. 引用不会“走错路”：引用一旦绑定就不能改指向" << endl;
    cout << "     指针可以随便指，指错地方就出大事" << endl;
    cout << endl;
    cout << "  结论：能传引用就传引用，指针留给更底层的场景" << endl;
    cout << "  但指针也必须会，C++很多地方离不开它" << endl;
    cout << "========================================" << endl;
    cout << endl;

    // ============================================================
    // 小练习
    // ============================================================
    cout << "========================================" << endl;
    cout << "  小练习（动手写写看）" << endl;
    cout << "========================================" << endl;
    cout << "  1. 写一个函数，判断一个数是不是质数" << endl;
    cout << "  2. 用引用传递写一个函数，同时返回两个数的和与积" << endl;
    cout << "     （提示：用两个引用参数当“返回值”）" << endl;
    cout << "  3. 写一个递归函数，求第n个斐波那契数" << endl;
    cout << "     然后想想怎么用循环实现，比较一下效率" << endl;
    cout << "  4. 实现一个函数重载：print 函数" << endl;
    cout << "     - print(int) 打印整数" << endl;
    cout << "     - print(double) 打印小数" << endl;
    cout << "     - print(string) 打印字符串" << endl;
    cout << "  5. 写一个函数，用静态变量统计自己被调用了多少次" << endl;
    cout << "========================================" << endl;

    return 0;
}
