#include <iostream>
#include <string>
using namespace std;

// 指针作函数参数：交换两个数
void swapByPtr(int *x, int *y)
{
    int temp = *x;
    *x = *y;
    *y = temp;
}

// 函数返回指针：在数组中查找某个值，返回它的地址
int* findValue(int arr[], int size, int target)
{
    for (int i = 0; i < size; i++) {
        if (arr[i] == target) {
            return &arr[i];  // 返回找到的元素的地址
        }
    }
    return nullptr;  // 没找到，返回空指针
}

// 引用作函数参数：交换两个数
void swapByRef(int &x, int &y)
{
    int temp = x;
    x = y;
    y = temp;
}

// const引用作参数（推荐！既能避免拷贝，又保证不修改原数据）
void printString(const string &s)
{
    // s = "modified";  // 错误！const引用不能修改
    cout << "字符串内容：" << s << "，长度：" << s.length() << endl;
}

int main()
{
    // ============================================================
    // 一、什么是指针
    // ============================================================
    // 老师傅比喻：指针就是"门牌号"，它存的不是东西本身，
    // 而是东西在内存里的"地址"。
    // 就像你要找一个人，你不需要把他揣兜里，
    // 你只要知道他家的门牌号，上门去找就行。
    cout << "===== 1. 什么是指针 =====" << endl;

    int var = 42;  // 一个普通变量，在内存里占一块地方

    // & 是"取地址运算符"，&var 就是 var 的内存地址
    cout << "var 的值：" << var << endl;
    cout << "var 的地址：" << &var << "（十六进制表示的内存地址）" << endl;
    cout << endl;

    // ============================================================
    // 二、指针的定义与使用
    // ============================================================
    cout << "===== 2. 指针的定义与使用 =====" << endl;

    // 定义指针：类型 *指针名;
    int *p;  // p是一个int类型的指针，它存的是int变量的地址
    // 老师傅提醒：*在定义时表示"这是个指针"，在使用时表示"取地址里的值"

    p = &var;  // 把 var 的地址存到 p 里，p 就"指向"了 var

    cout << "p 存的地址：" << p << endl;
    cout << "p 指向的值（*p）：" << *p << endl;
    // * 是"解引用运算符"，*p 就是"p指向的那个地址里存的值"

    // 通过指针修改原变量
    *p = 100;
    cout << "通过 *p = 100 修改后，var = " << var << endl;
    // 看到没？通过指针能直接改原变量的值！

    // 指针也有自己的地址（指针本身也是变量，也占内存）
    cout << "指针p自己的地址：" << &p << endl;
    cout << "指针本身的大小（64位系统）：" << sizeof(p) << "字节" << endl;
    // 老师傅说：不管什么类型的指针，大小都是一样的（32位系统4字节，64位8字节）
    // 因为地址长度是固定的，就像门牌号位数是固定的一样

    cout << endl;

    // ============================================================
    // 三、空指针
    // ============================================================
    // 老师傅说：空指针就是"不指向任何有效地址"的指针
    // 就像一个门牌号是"000号"，根本不存在这个地方
    cout << "===== 3. 空指针 =====" << endl;

    // C++11 推荐用 nullptr（类型安全的空指针）
    int *pNull = nullptr;

    // C语言风格的 NULL（本质是0，不推荐）
    int *pNULL = NULL;

    // 直接赋值0（也不推荐）
    int *pZero = 0;

    cout << "nullptr 的值：" << pNull << endl;
    cout << "NULL 的值：" << pNULL << endl;
    cout << "0 的值：" << pZero << endl;

    // 老师傅特别提醒：使用指针前一定要检查是不是空指针！
    // 解引用空指针会导致程序崩溃（段错误）
    if (pNull != nullptr) {
        cout << *pNull << endl;  // 不会执行到这里
    } else {
        cout << "pNull是空指针，不能解引用！" << endl;
    }

    cout << "为什么推荐 nullptr 而不是 NULL？" << endl;
    cout << "  - NULL本质是0，在函数重载时可能会搞错（int还是指针？）" << endl;
    cout << "  - nullptr是真正的指针类型，类型安全" << endl;
    cout << "  - C++11之后统一用 nullptr" << endl;
    cout << endl;

    // ============================================================
    // 四、指针与数组
    // ============================================================
    cout << "===== 4. 指针与数组 =====" << endl;

    int arr[] = {10, 20, 30, 40, 50};
    int *pArr = arr;  // 数组名就是首元素地址，直接赋值给指针

    cout << "数组首地址：" << arr << endl;
    cout << "pArr 的值：" << pArr << "（和数组首地址一样）" << endl;

    // 用指针遍历数组
    cout << "用指针遍历数组：";
    for (int i = 0; i < 5; i++) {
        cout << *(pArr + i) << " ";
        // pArr + i 是第i个元素的地址，*(pArr+i) 就是值
        // 等价于 pArr[i]，也等价于 arr[i]
    }
    cout << endl;

    // 指针加减运算（移动指针）
    int *p2 = &arr[0];
    cout << "p2 指向 arr[0]，值 = " << *p2 << endl;
    p2++;  // 指针加1，指向后一个元素
    cout << "p2++ 后，指向 arr[1]，值 = " << *p2 << endl;
    p2 += 2;  // 加2，往后跳两个元素
    cout << "p2 += 2 后，指向 arr[3]，值 = " << *p2 << endl;
    p2--;
    cout << "p2-- 后，指向 arr[2]，值 = " << *p2 << endl;

    // 指针相减：两个同类型指针相减，得到的是它们之间相差几个元素
    int *pStart = arr;
    int *pEnd = &arr[4];
    cout << "pEnd - pStart = " << (pEnd - pStart) << "（相差4个元素）" << endl;

    cout << endl;

    // ============================================================
    // 五、指针与函数
    // ============================================================
    cout << "===== 5. 指针与函数 =====" << endl;

    // 5.1 指针作函数参数（交换两个变量）
    int x = 10, y = 20;
    cout << "交换前：x = " << x << ", y = " << y << endl;
    swapByPtr(&x, &y);  // 传地址
    cout << "交换后：x = " << x << ", y = " << y << endl;

    // 5.2 函数返回指针
    int nums[] = {5, 10, 15, 20, 25};
    int *result = findValue(nums, 5, 15);
    if (result != nullptr) {
        cout << "找到了15，它的值是：" << *result << endl;
    } else {
        cout << "没找到" << endl;
    }

    result = findValue(nums, 5, 99);
    if (result == nullptr) {
        cout << "99没找到，返回了nullptr" << endl;
    }

    // 老师傅提醒：不要返回局部变量的地址！
    // 因为局部变量函数结束就销毁了，指针就变成"野指针"了
    // int* badExample() { int temp = 10; return &temp; }  // 大错特错！
    cout << endl;

    // ============================================================
    // 六、什么是引用
    // ============================================================
    // 老师傅比喻：引用就是"别名"，就像人的外号。
    // 你叫"张三"，外号"小张"，不管叫哪个，都是在叫你这个人。
    // 引用不是新变量，它只是原有变量的另一个名字。
    cout << "===== 6. 什么是引用 =====" << endl;

    int original = 100;
    int &ref = original;  // ref 是 original 的引用（别名）
    // & 在定义时跟在类型后面，表示"这是个引用类型"

    cout << "original = " << original << endl;
    cout << "ref = " << ref << "（和original一样）" << endl;
    cout << "&original = " << &original << endl;
    cout << "&ref = " << &ref << "（地址也一样，说明是同一个东西）" << endl;

    // 通过引用修改原变量
    ref = 200;
    cout << "ref = 200 后，original = " << original << endl;
    // 因为ref是original的别名，改ref就是改original

    cout << endl;

    // ============================================================
    // 七、引用与指针的区别（重点对比）
    // ============================================================
    cout << "===== 7. 引用与指针的区别 =====" << endl;

    int val = 42;
    int *ptr = &val;  // 指针
    int &ref2 = val;  // 引用

    cout << "           指针                    引用" << endl;
    cout << "-----------------------------------------" << endl;
    cout << "定义方式     int *p = &var;         int &r = var;" << endl;
    cout << "是否需要初始化  不一定（可以空）       必须初始化" << endl;
    cout << "可以为空吗     可以（nullptr）       不可以" << endl;
    cout << "能改指向吗     能                    不能（绑定后不变）" << endl;
    cout << "怎么用        要加*解引用           直接用就行" << endl;
    cout << "占内存吗      占（存地址）          不占额外内存" << endl;
    cout << "危险程度      高（野指针、空指针）    低（更安全）" << endl;

    cout << endl;
    cout << "用指针的时候：" << endl;
    cout << "  *ptr = 100;  // 要加*" << endl;
    cout << "用引用的时候：" << endl;
    cout << "  ref2 = 100;  // 直接用，就像普通变量" << endl;

    cout << endl;

    // ============================================================
    // 八、引用作函数参数（引用传递的优势）
    // ============================================================
    cout << "===== 8. 引用作函数参数 =====" << endl;

    int m = 10, n = 20;
    cout << "交换前：m = " << m << ", n = " << n << endl;
    swapByRef(m, n);  // 直接传变量名，不用取地址，多简洁！
    cout << "交换后：m = " << m << ", n = " << n << endl;

    // const引用的优势
    string bigStr = "这是一个很长的字符串...";
    printString(bigStr);  // 传引用，不用拷贝整个字符串，效率高
    // 而且const保证了函数不会乱改你的数据

    cout << endl;
    cout << "引用传递的三大优势：" << endl;
    cout << "  1. 语法简洁：调用时不用写&，函数里不用写*" << endl;
    cout << "  2. 更安全：不会有空指针、野指针的问题" << endl;
    cout << "  3. 效率高：传递大对象时不用拷贝（配合const更安全）" << endl;

    cout << endl;

    // ============================================================
    // 补充：const与指针
    // ============================================================
    cout << "===== 补充：const与指针 =====" << endl;

    int num = 10;
    int num2 = 20;

    // 指向常量的指针（指针指向的值不能改，但指针本身可以改指向）
    const int *pConstVal = &num;
    // *pConstVal = 100;  // 错误！不能通过这个指针修改值
    pConstVal = &num2;    // 可以，指针可以指向别的地方
    cout << "指向常量的指针：值不能通过指针改，但指针可以换指向" << endl;

    // 常量指针（指针本身不能改指向，但指向的值可以改）
    int *const pConstPtr = &num;
    *pConstPtr = 100;     // 可以，通过指针改值
    // pConstPtr = &num2;  // 错误！指针不能改指向
    cout << "常量指针：指针不能换指向，但值可以通过指针改" << endl;

    // 指向常量的常量指针（都不能改）
    const int *const pAllConst = &num;
    // *pAllConst = 100;  // 错误
    // pAllConst = &num2; // 错误
    cout << "指向常量的常量指针：两者都不能改" << endl;

    // 老师傅教你怎么记：从右往左读
    // const int *p  -> p 是指针，指向 int const（常量int）
    // int *const p  -> p 是 const（常量），是指针，指向int
    cout << endl;

    // ============================================================
    // 老师傅的话：指针是C++的双刃剑，要敬畏
    // ============================================================
    cout << "========================================" << endl;
    cout << "  老师傅的话：指针是C++的双刃剑" << endl;
    cout << "========================================" << endl;
    cout << "  指针是C++最强大的武器，也是最危险的陷阱" << endl;
    cout << endl;
    cout << "  指针的威力：" << endl;
    cout << "    1. 直接操作内存，效率极高" << endl;
    cout << "    2. 实现动态内存分配（new/delete）" << endl;
    cout << "    3. 操作数组、字符串、函数指针等" << endl;
    cout << "    4. 实现复杂数据结构（链表、树、图）" << endl;
    cout << endl;
    cout << "  指针的危险：" << endl;
    cout << "    1. 空指针解引用 -> 程序崩溃" << endl;
    cout << "    2. 野指针（指向已释放内存）-> 神秘bug" << endl;
    cout << "    3. 越界访问 -> 破坏其他数据" << endl;
    cout << "    4. 内存泄漏（忘记释放）-> 程序越来越卡" << endl;
    cout << endl;
    cout << "  给初学者的建议：" << endl;
    cout << "    1. 传参优先用引用，指针留给必要的场景" << endl;
    cout << "    2. 指针用完及时置空，避免野指针" << endl;
    cout << "    3. 解引用前先检查是不是空指针" << endl;
    cout << "    4. new和delete要配对，有借有还" << endl;
    cout << "    5. 多练多想，指针这东西，用多了就熟了" << endl;
    cout << "========================================" << endl;
    cout << endl;

    // ============================================================
    // 小练习
    // ============================================================
    cout << "========================================" << endl;
    cout << "  小练习（动手写写看）" << endl;
    cout << "========================================" << endl;
    cout << "  1. 写一个函数，用指针交换两个int变量的值" << endl;
    cout << "  2. 写一个函数，用引用交换两个string变量的值" << endl;
    cout << "  3. 用指针遍历一个数组，求所有元素的和" << endl;
    cout << "  4. 写一个函数，接收一个数组和它的大小，" << endl;
    cout << "     用指针把数组元素反转（首尾交换）" << endl;
    cout << "  5. 写一个函数，用引用返回三个数中的最大值" << endl;
    cout << "     （提示：返回类型是 int&，返回最大值的引用）" << endl;
    cout << "  6. 理解const与指针的三种组合，自己写代码验证" << endl;
    cout << "========================================" << endl;

    return 0;
}
