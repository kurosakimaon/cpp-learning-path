// ============================================================================
// 一、什么是面向对象？（对比面向过程）
// ============================================================================
// 徒弟啊，咱们先唠唠什么是面向对象。
//
// 【面向过程】就像你按照菜谱炒菜：
//   第一步：洗菜 -> 第二步：切菜 -> 第三步：倒油 -> 第四步：下锅 -> 第五步：放盐...
//   强调的是"做什么"，是一步一步的流程。
//
// 【面向对象】就像你开饭店：
//   有厨师（负责炒菜）、有服务员（负责端菜）、有收银员（负责收钱）
//   每个"对象"有自己的职责，大家配合完成工作。
//   强调的是"谁来做"，把数据和操作数据的函数绑在一起。
//
// 面向对象的三大特性：封装、继承、多态。今天咱们先讲第一个——封装。
// ============================================================================

// ============================================================================
// 二、类的定义 & 三、访问控制（封装）
// ============================================================================
// 类就像一张图纸，对象就是用这张图纸造出来的具体东西。
// 比如"汽车图纸"是类，"你家那辆红色小轿车"就是对象。
//
// 访问控制有三个关键字，就像三道门：
//   public    - 公开的，谁都能进来（大厅）
//   private   - 私有的，只有自己家人能进（卧室）
//   protected - 受保护的，自己家人和子女能进（家族祠堂）
//
// 【封装的意义】：把数据藏起来（private），只留接口给外面用（public）。
// 就像电视机，你不用管里面电路板怎么工作，按遥控器就行。
// ============================================================================

// 咱们用一个"人"的例子来讲解
class Person {
// ===== 私有成员：外面不能直接访问，被"封装"起来了 =====
private:
    string  name;       // 姓名
    int     age;        // 年龄
    double  salary;     // 工资（这是隐私，不能随便看）

    // 私有成员函数：内部使用的工具函数，外面不需要知道
    bool isSalaryValid(double s) {
        return s >= 0;  // 工资不能是负数
    }

// ===== 公有成员：对外的接口，别人通过这些函数来操作对象 =====
public:

    // ========================================================================
    // 四、构造函数
    // ========================================================================
    // 徒弟你记住：构造函数就是"出生函数"，对象创建的时候自动调用。
    // 特点：名字和类名一样，没有返回值（连void都不写）。
    // ========================================================================

    // --- 默认构造函数（无参构造）---
    // 就像一个人生下来还没起名字，先给个默认值
    Person() {
        name   = "无名氏";
        age    = 0;
        salary = 0.0;
        cout << "【构造】默认构造函数被调用了：" << name << " 出生了" << endl;
    }

    // --- 带参构造函数 ---
    // 生下来就有名字有年龄
    Person(string n, int a, double s) {
        name   = n;
        age    = a;
        salary = s;
        cout << "【构造】带参构造函数被调用了：" << name << " 出生了" << endl;
    }

    // --- 初始化列表写法（推荐！效率更高）---
    // 注意看，冒号后面直接给成员变量赋值，这叫"初始化列表"
    // 区别：构造函数体内是"赋值"，初始化列表是"初始化"
    // 就像盖房子：初始化列表是打地基时就定好尺寸，函数体内是盖完了再改
    Person(string n) : name(n), age(18), salary(3000.0) {
        cout << "【构造】初始化列表构造：" << name << " 出生了，默认年龄18" << endl;
    }

    // ========================================================================
    // 五、析构函数
    // ========================================================================
    // 析构函数就是"死亡函数"，对象销毁的时候自动调用。
    // 特点：名字是 ~类名，没有返回值，没有参数。
    // 作用：清理资源（释放内存、关闭文件等）
    // ========================================================================
    ~Person() {
        delete[] address;
        cout << "【析构】析构函数被调用了：" << name << " 走了..." << endl;
    }

    // ========================================================================
    // 六、拷贝构造函数
    // ========================================================================
    // 拷贝构造：用一个已有的对象，克隆出一个新对象。
    // 特点：参数是 const 类名& （常量引用）
    //
    // 【浅拷贝 vs 深拷贝】这是个大坑！徒弟你听好了：
    //   浅拷贝：简单地把值复制过去。如果有指针成员，两个对象指向同一块内存，
    //          一个释放了另一个就变成野指针了！
    //   深拷贝：重新分配内存，把内容复制过去。各自有各自的内存，互不影响。
    //
    // 编译器默认给的拷贝构造是浅拷贝，有指针成员时必须自己写深拷贝！
    // ========================================================================

    // 先加一个指针成员，用来演示深浅拷贝问题
private:
    char* address = nullptr;  // 住址（用char*指针，故意用来演示深浅拷贝）

public:
    // 设置住址的函数（顺便演示深拷贝的需求）
    void setAddress(const char* addr) {
        // 先分配并复制新内容，成功后再释放旧内容。
        // 如果先 delete 再 new，而 new 抛异常，对象就丢了原数据；
        // 若 addr 恰好指向自己的旧缓冲区，先 delete 还会读到已释放内存。
        size_t len = strlen(addr) + 1;
        char* fresh = new char[len];
        strcpy(fresh, addr);
        delete[] address;
        address = fresh;
    }

    const char* getAddress() const {
        return address ? address : "无";
    }

    // 自己写的拷贝构造函数 —— 深拷贝版本
    Person(const Person& other)
        : name(other.name), age(other.age), salary(other.salary), address(nullptr) {
        // 关键！指针成员要重新分配内存，然后复制内容
        if (other.address != nullptr) {
            size_t len = strlen(other.address) + 1;
            address = new char[len];
            strcpy(address, other.address);
        }

        cout << "【拷贝构造】深拷贝了一个人：" << name << endl;
    }

    // 拷贝赋值运算符 —— 同样要深拷贝，并处理自赋值
    Person& operator=(const Person& other) {
        if (this == &other) {
            return *this;
        }
        // 先准备好一份新拷贝，再替换旧资源：
        // 这样 new 抛异常时，原对象仍然完整（强异常安全）。
        char* fresh = nullptr;
        if (other.address != nullptr) {
            size_t len = strlen(other.address) + 1;
            fresh = new char[len];
            strcpy(fresh, other.address);
        }
        delete[] address;
        address = fresh;
        name   = other.name;
        age    = other.age;
        salary = other.salary;
        return *this;
    }

    // ========================================================================
    // 七、this 指针
    // ========================================================================
    // this 是一个特殊的指针，指向"当前对象"自己。
    // 就像你说"我"的时候，指的是你自己。
    // 什么时候用？
    //   1. 参数名和成员变量同名时，用 this-> 区分
    //   2. 链式调用（返回 *this）
    //   3. 确定当前对象的地址
    // ========================================================================

    // 例子1：参数名和成员变量同名
    void setName(string name) {
        // 左边 this->name 是成员变量，右边 name 是参数
        this->name = name;
    }

    // 例子2：链式调用（返回 *this，就能连续调用）
    Person& setAge(int age) {
        this->age = age;
        return *this;  // 返回当前对象的引用
    }

    Person& setSalary(double salary) {
        if (isSalaryValid(salary)) {
            this->salary = salary;
        }
        return *this;
    }

    // ========================================================================
    // 八、静态成员变量与静态成员函数
    // ========================================================================
    // 静态成员属于"整个类"，不属于某个具体对象。
    // 就像"人类总数"是全人类的属性，不是某个人的属性。
    //
    // 静态成员变量：所有对象共享同一份数据，要在类外面初始化
    // 静态成员函数：只能访问静态成员变量，没有 this 指针
    // ========================================================================

private:
    static int personCount;  // 静态成员变量：统计创建了多少个人

public:
    // 静态成员函数：获取总人数
    static int getPersonCount() {
        // 静态函数里不能用 this，也不能访问非静态成员
        return personCount;
    }

    // 注意：我们需要在构造函数里让计数器+1，析构函数里-1
    // （上面的构造函数我故意没加，等下在完整例子里补上，这里先讲概念）

    // ========================================================================
    // 普通成员函数（对外接口）
    // ========================================================================

    // 自我介绍
    void introduce() const {  // 后面加 const 表示这个函数不会修改成员变量
        cout << "大家好，我叫" << name
             << "，今年" << age << "岁"
             << "，住在" << getAddress() << endl;
    }

    // 获取工资（只读接口，保护数据）
    double getSalary() const {
        // 外面想看工资？可以，但只能看，不能改（除非走 setSalary 接口）
        return salary;
    }

    // 过生日（年龄+1）
    void birthday() {
        age++;
        cout << name << " 过生日啦！今年 " << age << " 岁" << endl;
    }
};

// 静态成员变量必须在类外面初始化！（这是规定，记住就行）
int Person::personCount = 0;

// 等一下，上面的构造函数我没加 personCount++，咱们再写一个"完整版本"的类来演示
// 不然例子跑起来不对。为了代码清晰，咱们重新定义一个带完整计数的类。

// --- 一个更完整的演示类，用来展示静态成员 ---
class Student {
private:
    string name;
    int    score;

    static int studentCount;  // 学生总数

public:
    // 默认构造
    Student() : name("未知"), score(0) {
        studentCount++;
        cout << "【Student】新同学来了，当前共 " << studentCount << " 人" << endl;
    }

    // 带参构造
    Student(string n, int s) : name(n), score(s) {
        studentCount++;
        cout << "【Student】" << name << " 同学来了，当前共 " << studentCount << " 人" << endl;
    }

    // 析构
    ~Student() {
        studentCount--;
        cout << "【Student】" << name << " 同学走了，还剩 " << studentCount << " 人" << endl;
    }

    // 静态成员函数
    static int getCount() {
        return studentCount;
    }

    void showInfo() const {
        cout << "  学生：" << name << "，分数：" << score << endl;
    }
};

// 静态成员变量类外初始化
int Student::studentCount = 0;

// ============================================================================
// 主函数：所有知识点的演示入口
// ============================================================================
int main() {
    cout << "==================== 07 - 类与对象基础 ====================" << endl;
    cout << endl;

    // ---- 1. 构造函数演示 ----
    cout << "--- 1. 构造函数演示 ---" << endl;
    {
        Person p1;                    // 默认构造
        Person p2("张三", 25, 8000);  // 带参构造
        Person p3("李四");            // 初始化列表构造
    }  // 出了大括号，对象就销毁了，会自动调用析构函数
    cout << endl;

    // ---- 2. 封装演示：private 成员不能直接访问 ----
    cout << "--- 2. 封装演示 ---" << endl;
    Person wangwu("王五", 30, 15000);
    wangwu.introduce();
    // wangwu.salary = 20000;  // 这行写了会报错！salary是private的
    cout << "王五的工资是：" << wangwu.getSalary() << "（只能通过接口读取）" << endl;

    // 工资要修改必须走 setSalary 接口，接口里可以做合法性检查
    wangwu.setSalary(-5000);  // 负数，不会生效
    cout << "尝试设置负数工资后，实际工资：" << wangwu.getSalary() << endl;
    wangwu.setSalary(20000);  // 合法，生效
    cout << "设置合法工资后，实际工资：" << wangwu.getSalary() << endl;
    cout << endl;

    // ---- 3. this 指针和链式调用演示 ----
    cout << "--- 3. this 指针与链式调用 ---" << endl;
    Person zhaoliu("赵六");
    // 链式调用：因为 setAge 和 setSalary 返回 *this，所以可以连着写
    zhaoliu.setAge(28).setSalary(12000);
    zhaoliu.introduce();
    cout << endl;

    // ---- 4. 深浅拷贝演示 ----
    cout << "--- 4. 深拷贝与浅拷贝 ---" << endl;
    Person qianqi("钱七");
    qianqi.setAddress("北京市朝阳区");
    cout << "钱七的住址：" << qianqi.getAddress() << endl;

    Person qianqi2 = qianqi;  // 调用拷贝构造函数（深拷贝）
    cout << "钱七2号（克隆的）住址：" << qianqi2.getAddress() << endl;

    // 修改钱七的住址，看看会不会影响钱七2号
    qianqi.setAddress("上海市浦东新区");
    cout << "修改后——钱七的住址：" << qianqi.getAddress() << endl;
    cout << "修改后——钱七2号的住址：" << qianqi2.getAddress()
         << "（没变！因为是深拷贝，各自有各自的内存）" << endl;
    cout << endl;

    // ---- 5. 静态成员演示 ----
    cout << "--- 5. 静态成员变量与静态成员函数 ---" << endl;
    cout << "最开始，学生总数：" << Student::getCount() << "（用 类名::函数名 调用）" << endl;

    Student s1("小明", 95);
    Student s2("小红", 88);
    Student s3;  // 默认构造

    cout << "现在一共有多少学生？" << endl;
    cout << "  通过类名调用：" << Student::getCount() << " 人" << endl;
    cout << "  通过对象调用：" << s1.getCount() << " 人（结果一样，因为共享同一份数据）" << endl;

    s1.showInfo();
    s2.showInfo();
    s3.showInfo();
    cout << endl;

    cout << "=================== 程序结束 ===================" << endl;

    return 0;
}

