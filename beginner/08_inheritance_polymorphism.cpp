// 老师傅的话
// ============================================================================
/*
 * 徒弟啊，今天讲的多态，是面向对象编程的精髓，你一定要理解透。
 *
 * 【多态到底好在哪？】
 *
 * 我给你举个例子：你要写一个画图软件，支持画圆、画方、画三角形。
 *
 * 如果不用多态，你可能要写：
 *   if (类型 == 圆) 画圆();
 *   else if (类型 == 方) 画方();
 *   else if (类型 == 三角) 画三角();
 *
 * 以后加个新形状？你得找到所有这种 if-else 的地方，再加一条。
 * 代码散得到处都是，容易漏，容易错。
 *
 * 用了多态呢？你就写一句：shape->draw();
 * 它自己知道该怎么画。加新形状？加个新类就行，老代码一行都不用改。
 * 这叫"开闭原则"：对扩展开放，对修改关闭。
 *
 * 【几个要注意的坑】
 *
 * 1. 基类析构函数一定要是 virtual 的！
 *    不然用基类指针 delete 子类对象是未定义行为：
 *    常见后果是派生类析构不执行、资源泄漏，但标准并不保证"只是泄漏"。
 *
 * 2. 重写函数时，参数列表、返回值、const 都要一模一样，不然不是重写。
 *    推荐加 override 关键字，让编译器帮你检查。
 *
 * 3. 多重继承尽量少用，容易出菱形问题。
 *    真要用的话，考虑是不是应该用接口（纯虚函数的抽象类）。
 *
 * 【口诀】
 *   继承就是子类用父类，
 *   公有继承最常用，
 *   构造先爹后儿子，
 *   析构先儿后老爹，
 *   虚函数是多态根，
 *   基类析构要加虚，
 *   重写加上 override，
 *   纯虚函数成抽象，
 *   菱形继承用虚继。
 *
 * 【小练习】
 *   1. 写一个 Employee 基类，有 name 和 salary 属性，有一个虚函数 work()。
 *   2. 派生出 Programmer（程序员）和 Manager（经理）两个类，重写 work()。
 *   3. 用 Employee* 数组存几个不同的员工，遍历调用 work()，看看多态效果。
 *   4. 再增加一个 Designer（设计师）类，看看加新类有多方便。
 *   5. 试试不把基类析构写成虚的，delete 基类指针看看会发生什么。
 *
 *  多态这东西，光看不练不行。回去敲代码，敲着敲着就懂了。
 */
