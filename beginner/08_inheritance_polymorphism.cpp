#include <iostream>
#include <string>

using namespace std;

// ============================================================================
// 一、继承的概念与语法
// ============================================================================
// 徒弟啊，继承就是"儿子继承老子的财产"。
// 父类（基类）有的东西，子类（派生类）自动就有了，不用再写一遍。
//
// 生活中的例子：
//   动物 -> 哺乳动物 -> 人 -> 学生
//   交通工具 -> 汽车 -> 电动车
//
// 这叫 "is-a" 关系：学生 "是一个" 人，电动车 "是一种" 汽车。
//
// 语法：class 子类 : 继承方式 父类
// ============================================================================

// --- 基类：动物 ---
class Animal {
protected:  // 保护的：子类能访问，外面不能访问
    string name;    // 名字
    int    age;     // 年龄

public:
    // 构造函数
    Animal(string n, int a) : name(n), age(a) {
        cout << "【Animal 构造】" << name << " 出生了" << endl;
    }

    // 析构函数
    ~Animal() {
        cout << "【Animal 析构】" << name << " 走了" << endl;
    }

    // 吃东西（所有动物都会吃）
    void eat() {
        cout << name << " 在吃东西" << endl;
    }

    // 睡觉
    void sleep() {
        cout << name << " 在睡觉 zzz..." << endl;
    }

    // 介绍自己（注意：这个函数不是虚函数！）
    void introduce() {
        cout << "我是一只动物，叫" << name << "，今年" << age << "岁" << endl;
    }

    // 获取名字
    string getName() const { return name; }
};

// ============================================================================
// 二、公有继承、保护继承、私有继承
// ============================================================================
// 继承方式有三种，决定了父类成员在子类中的访问权限：
//
//  1. public 公有继承（最常用，99%的情况用这个）
//     父类的 public   -> 子类的 public
//     父类的 protected-> 子类的 protected
//     父类的 private  -> 子类不可直接访问
//     一句话：爹是什么样，儿子还是什么样。
//
//  2. protected 保护继承
//     父类的 public   -> 子类的 protected
//     父类的 protected-> 子类的 protected
//     父类的 private  -> 子类不可直接访问
//     一句话：爹的公开财产，到儿子这就变成家族内部的了。
//
//  3. private 私有继承（用得最少）
//     父类的 public   -> 子类的 private
//     父类的 protected-> 子类的 private
//     父类的 private  -> 子类不可直接访问
//     一句话：爹的所有东西，到儿子这都变成私有的了。
//
//  徒弟你记住：一般就用 public 继承，其他两种知道有这么回事就行。
// ============================================================================

// --- 派生类：狗（公有继承动物）---
class Dog : public Animal {
private:
    string breed;   // 品种

public:
    // ========================================================================
    // 三、派生类的构造与析构顺序
    // ========================================================================
    // 构造顺序：先父类，再子类（先生爹后生儿子，天经地义）
    // 析构顺序：先子类，再父类（儿子先走，爹善后）
    //
    // 注意：子类构造函数要调用父类的构造函数，用初始化列表
    // ========================================================================

    Dog(string n, int a, string b) : Animal(n, a), breed(b) {
        cout << "【Dog 构造】" << name << " 是一只" << breed << endl;
    }

    ~Dog() {
        cout << "【Dog 析构】" << name << " 这条狗走了" << endl;
    }

    // 狗特有的行为：汪汪叫
    void bark() {
        cout << name << " 汪汪汪！" << endl;
    }

    // ========================================================================
    // 四、函数隐藏（hiding）—— 注意这不是重写
    // ========================================================================
    // 父类的 introduce 不是虚函数，子类再写一个同名函数，
    // 这叫"隐藏"（name hiding），不是重写（override），也不构成多态。
    // 用 Dog 对象调用时看到的是 Dog 版本；但通过 Animal* 调用，
    // 仍然会调用 Animal::introduce。真正的重写要求父类函数是 virtual。
    // ========================================================================

    // 隐藏父类的 introduce（不是重写！）
    void introduce() {
        cout << "我是一只狗，叫" << name << "，今年" << age << "岁，品种是" << breed << endl;
    }
};

// ============================================================================
// 五、虚函数与多态（核心中的核心！）
// ============================================================================
// 徒弟，这是面向对象最精髓的东西，你可得竖起耳朵听好了。
//
// 什么是多态？—— "同一个接口，不同的实现"。
// 就像"动物叫"这个动作：狗汪汪叫，猫喵喵叫，鸟叽叽叫。
// 都是"叫"，但每种动物的叫法不一样。
//
// 怎么实现多态？四个条件：
//   1. 要有继承关系
//   2. 父类要有虚函数（virtual）
//   3. 子类要重写这个虚函数
//   4. 用父类指针/引用指向子类对象
//
// 调用的时候，看的是"实际指向的对象类型"，不是"指针的类型"。
// 这叫"动态绑定"——运行时才确定调用哪个函数。
// ============================================================================

// --- 我们重新定义一套带虚函数的类体系 ---

// 基类：形状（抽象的概念）
class Shape {
protected:
    string color;

public:
    Shape(string c) : color(c) {
        // 空的，就初始化个颜色
    }

    virtual ~Shape() {
        // 基类析构函数一定要是虚的！
        // 否则通过基类指针 delete 派生类对象是未定义行为
        //（通常会跳过派生类析构，但不保证只是"泄漏"这么简单）
        cout << "【Shape 析构】销毁一个形状" << endl;
    }

    // ===== 虚函数：求面积 =====
    // 加了 virtual 关键字，就表示这个函数可以被子类重写，支持多态
    virtual double getArea() const {
        return 0.0;  // 基类不知道具体形状，返回0
    }

    // ===== 虚函数：显示信息 =====
    virtual void showInfo() const {
        cout << "这是一个形状，颜色：" << color << endl;
    }

    string getColor() const { return color; }
};

// 派生类：圆形
class Circle : public Shape {
private:
    double radius;

public:
    Circle(string c, double r) : Shape(c), radius(r) {}

    ~Circle() {
        cout << "【Circle 析构】销毁一个圆形" << endl;
    }

    // 重写 getArea（override 关键字可选，但推荐加上，让编译器帮你检查）
    double getArea() const override {
        return 3.1415926 * radius * radius;
    }

    void showInfo() const override {
        cout << "这是一个圆形，颜色：" << color
             << "，半径：" << radius
             << "，面积：" << getArea() << endl;
    }
};

// 派生类：矩形
class Rectangle : public Shape {
private:
    double width;
    double height;

public:
    Rectangle(string c, double w, double h) : Shape(c), width(w), height(h) {}

    ~Rectangle() {
        cout << "【Rectangle 析构】销毁一个矩形" << endl;
    }

    double getArea() const override {
        return width * height;
    }

    void showInfo() const override {
        cout << "这是一个矩形，颜色：" << color
             << "，宽：" << width
             << "，高：" << height
             << "，面积：" << getArea() << endl;
    }
};

// 派生类：三角形
class Triangle : public Shape {
private:
    double base;
    double height;

public:
    Triangle(string c, double b, double h) : Shape(c), base(b), height(h) {}

    ~Triangle() {
        cout << "【Triangle 析构】销毁一个三角形" << endl;
    }

    double getArea() const override {
        return 0.5 * base * height;
    }

    void showInfo() const override {
        cout << "这是一个三角形，颜色：" << color
             << "，底：" << base
             << "，高：" << height
             << "，面积：" << getArea() << endl;
    }
};

// ============================================================================
// 六、虚函数表原理通俗解释
// ============================================================================
// 徒弟，你可能好奇：虚函数到底是怎么实现多态的？为啥调同一个函数，结果不一样？
//
// 我给你打个比方：
//
// 每个有虚函数的类，都有一张"虚函数表"（vtable），就像一个菜单。
// 菜单上写着：这个类的虚函数分别对应哪个真实的函数。
//
// 每个对象里，都有一个"虚函数表指针"（vptr），就像一个指向菜单的小纸条。
// 对象创建的时候，这个指针会自动指向自己类的那张菜单。
//
// 当你用父类指针调用虚函数时：
//   1. 先看这个指针实际指向的对象是谁
//   2. 找到这个对象的 vptr
//   3. 通过 vptr 找到 vtable（菜单）
//   4. 从菜单里找到对应的函数，调用它
//
// 这就是"动态绑定"——运行时才确定调用谁。
// 代价就是多了一点点内存（每个对象多一个指针）和一点点时间（查表）。
//
// 注意：普通函数没有这张表，编译时就确定调用谁了，叫"静态绑定"。
// ============================================================================

// ============================================================================
// 七、纯虚函数与抽象类
// ============================================================================
// 纯虚函数：声明为 = 0 的虚函数，通常不在类内给实现。
// 语法：virtual 返回类型 函数名(参数) = 0;
// 注意：纯虚函数也可以有函数体（定义），但派生类仍必须重写它，
// 否则派生类依然是抽象类（不能创建对象）。
//
// 有纯虚函数的类，叫"抽象类"——不能直接创建对象（太抽象了，没法实例化）。
// 就像"动物"是抽象的，你没法养一只"抽象的动物"，只能养猫养狗。
//
// 抽象类的作用：定义"接口规范"，要求想实例化的派生类实现这些函数。
// ============================================================================

// --- 一个更纯粹的抽象基类：飞行器 ---
class Flyable {
public:
    virtual ~Flyable() {}  // 虚析构，必须有

    // 纯虚函数：飞行
    // 只要继承 Flyable，就必须实现 fly 函数，不然编译报错
    virtual void fly() = 0;

    // 纯虚函数：降落
    virtual void land() = 0;
};

// 派生类：飞机
class Airplane : public Flyable {
private:
    string name;

public:
    Airplane(string n) : name(n) {}

    void fly() override {
        cout << name << " 飞机在万米高空飞行 ✈" << endl;
    }

    void land() override {
        cout << name << " 飞机平稳降落" << endl;
    }
};

// 派生类：鸟
class Bird : public Flyable {
private:
    string species;  // 种类

public:
    Bird(string s) : species(s) {}

    void fly() override {
        cout << species << " 扇动翅膀飞翔 🐦" << endl;
    }

    void land() override {
        cout << species << " 停在了树枝上" << endl;
    }
};

// ============================================================================
// 八、菱形继承与虚继承
// ============================================================================
// 徒弟，菱形继承是个坑，你得知道怎么回事。
//
// 什么是菱形继承？就是这样：
/*       A（动物）
 *      / \ 
 *     B   C（哺乳动物 和 会飞的动物）
 *      \ /
 *       D（蝙蝠：既是哺乳动物，又会飞）
 */
//
// 问题来了：D 继承了 B 和 C，而 B 和 C 都继承了 A。
// 那 D 里面有几份 A 的数据？—— 两份！这就有歧义了。
//
// 解决方案：虚继承（virtual inheritance）
// 让 B 和 C 都虚继承 A，这样 D 里面就只有一份 A 的数据了。
//
// 徒弟你记住：实际开发中尽量避免多重继承，容易搞出菱形问题。
// 如果真要用，记得加 virtual。
// ============================================================================

// --- 菱形继承的例子 ---

// 最顶层：动物
class Animal_base {
protected:
    int age;
public:
    Animal_base() : age(0) {
        cout << "【Animal_base 构造】" << endl;
    }
    void setAge(int a) { age = a; }
    int getAge() const { return age; }
};

// 中间层1：哺乳动物（虚继承）
class Mammal : virtual public Animal_base {
public:
    void giveBirth() {
        cout << "胎生繁殖" << endl;
    }
};

// 中间层2：会飞的动物（虚继承）
class WingedAnimal : virtual public Animal_base {
public:
    void flapWings() {
        cout << "扇动翅膀" << endl;
    }
};

// 最底层：蝙蝠（继承了两个中间类）
class Bat : public Mammal, public WingedAnimal {
public:
    void echolocate() {
        cout << "蝙蝠用超声波定位" << endl;
    }
    // 因为用了虚继承，这里只有一份 age，不会有歧义
};

// ============================================================================
// 主函数
// ============================================================================
int main() {
    cout << "==================== 08 - 继承与多态 ====================" << endl;
    cout << endl;

    // ---- 1. 继承基础演示 ----
    cout << "--- 1. 继承基础：狗继承自动物 ---" << endl;
    {
        Dog dog("旺财", 3, "中华田园犬");
        dog.eat();       // 父类的方法，直接用
        dog.sleep();     // 父类的方法
        dog.bark();      // 子类自己的方法
        dog.introduce(); // 子类同名函数隐藏了父类方法（不是虚函数重写）
    }
    // 你可以从输出看到构造顺序：Animal -> Dog
    // 析构顺序：Dog -> Animal
    cout << endl;

    // ---- 2. 虚函数与多态演示（重头戏！）----
    cout << "--- 2. 虚函数与多态：形状的面积 ---" << endl;

    // 用基类指针数组，存各种不同的形状
    // 这就是多态的威力：同一个数组，放不同类型的对象，调用同一个函数，结果不一样
    Shape* shapes[5];
    shapes[0] = new Circle("红色", 5.0);
    shapes[1] = new Rectangle("蓝色", 4.0, 6.0);
    shapes[2] = new Triangle("绿色", 3.0, 8.0);
    shapes[3] = new Circle("黄色", 2.5);
    shapes[4] = new Rectangle("紫色", 5.0, 5.0);

    cout << endl;
    cout << "遍历所有形状，计算总面积：" << endl;
    double totalArea = 0;
    for (int i = 0; i < 5; i++) {
        shapes[i]->showInfo();
        totalArea += shapes[i]->getArea();
    }
    cout << "总面积：" << totalArea << endl;
    cout << endl;

    // 释放内存（因为析构函数是虚的，所以会正确调用子类析构）
    cout << "开始释放形状：" << endl;
    for (int i = 0; i < 5; i++) {
        delete shapes[i];
    }
    cout << endl;

    // ---- 3. 纯虚函数与抽象类演示 ----
    cout << "--- 3. 纯虚函数与抽象类：飞行器 ---" << endl;
    // Flyable f;  // 这行写了会报错！抽象类不能实例化

    Flyable* flyers[3];
    flyers[0] = new Airplane("波音747");
    flyers[1] = new Bird("麻雀");
    flyers[2] = new Airplane("歼20");

    cout << endl << "起飞！" << endl;
    for (int i = 0; i < 3; i++) {
        flyers[i]->fly();
    }

    cout << endl << "降落！" << endl;
    for (int i = 0; i < 3; i++) {
        flyers[i]->land();
    }
    cout << endl;

    for (int i = 0; i < 3; i++) {
        delete flyers[i];
    }
    cout << endl;

    // ---- 4. 菱形继承与虚继承演示 ----
    cout << "--- 4. 菱形继承与虚继承：蝙蝠 ---" << endl;
    Bat bat;
    bat.setAge(2);  // 虚继承后，只有一份 age，没有歧义
    cout << "蝙蝠的年龄：" << bat.getAge() << " 岁" << endl;
    bat.giveBirth();     // 来自哺乳动物
    bat.flapWings();     // 来自会飞的动物
    bat.echolocate();    // 自己的
    cout << endl;

    cout << "=================== 程序结束 ===================" << endl;

    return 0;
}

