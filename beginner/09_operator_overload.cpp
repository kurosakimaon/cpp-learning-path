#include <iostream>
#include <string>
#include <cstring>

using namespace std;

// ============================================================================
// 一、为什么需要运算符重载
// ============================================================================
// 徒弟啊，你想啊，int 类型可以直接 + - * /，对吧？
// 那我自己写的"复数"类、"向量"类、"字符串"类，能不能也用 + 号相加？
//
// 答案是可以的——这就是运算符重载。
//
// 运算符重载的本质：给已有的运算符赋予新的含义，让自定义类型也能用运算符。
// 就像 + 号，对 int 是加法，对 string 是拼接，对复数是复数加法。
//
// 规则：
//   1. 不能发明新的运算符（你不能搞个 @ 运算符出来）
//   2. 不能改变运算符的优先级和结合性
//   3. 不能改变操作数个数（二元运算符还是两个操作数）
//   4. 有些运算符不能重载（比如 .  ::  sizeof  ?: 等）
// ============================================================================

// ============================================================================
// 二、成员函数 vs 全局函数重载
// ============================================================================
// 运算符重载有两种写法：
//
// 1. 成员函数方式：运算符函数作为类的成员
//    特点：左操作数是 this，右操作数是参数
//    优点：能直接访问私有成员
//
// 2. 全局函数方式：运算符函数是普通函数
//    特点：两个操作数都是参数
//    优点：左操作数可以是其他类型（比如 int + MyClass）
//    如果要访问私有成员，需要声明为友元
//
// 什么时候用哪种？
//   - 赋值=、下标[]、函数调用()、成员访问-> 必须是成员函数
//   - 算术运算符一般用全局函数（支持交换律）
//   - 其他的看情况
// ============================================================================

// --- 咱们用"复数"类来演示运算符重载 ---
// 复数：a + bi，比如 3 + 4i
class Complex {
private:
    double real;   // 实部
    double imag;   // 虚部

public:
    // 构造函数
    Complex(double r = 0, double i = 0) : real(r), imag(i) {}

    // 打印复数
    void print() const {
        cout << real;
        if (imag >= 0) cout << " + " << imag << "i";
        else           cout << " - " << -imag << "i";
        cout << endl;
    }

    // ========================================================================
    // 三、算术运算符（+ - * /）
    // ========================================================================

    // --- 成员函数方式重载 + 号 ---
    // 左操作数：this（当前对象）
    // 右操作数：other（参数）
    Complex operator+(const Complex& other) const {
        return Complex(real + other.real, imag + other.imag);
    }

    // --- 成员函数方式重载 - 号 ---
    Complex operator-(const Complex& other) const {
        return Complex(real - other.real, imag - other.imag);
    }

    // --- 声明 * 和 / 用全局函数方式，需要友元才能访问私有成员 ---
    friend Complex operator*(const Complex& a, const Complex& b);
    friend Complex operator/(const Complex& a, const Complex& b);

    // ========================================================================
    // 四、关系运算符（== != < >）
    // ========================================================================
    // 比较两个复数是否相等（实部虚部都相等才相等）
    bool operator==(const Complex& other) const {
        return real == other.real && imag == other.imag;
    }

    bool operator!=(const Complex& other) const {
        return !(*this == other);  // 复用 == 的逻辑
    }

    // 复数其实没有天然的大小关系，这里我们比较模长（举例用）
    double magnitude() const {
        return real * real + imag * imag;  // 模长的平方，省得开根号
    }

    bool operator<(const Complex& other) const {
        return this->magnitude() < other.magnitude();
    }

    bool operator>(const Complex& other) const {
        return other < *this;  // 复用 < 的逻辑（聪明的写法）
    }

    // ========================================================================
    // 五、赋值运算符（=）
    // ========================================================================
    // 赋值运算符必须是成员函数！
    // 注意：和拷贝构造一样，默认赋值运算符是浅拷贝，有指针成员时必须自己写。
    // 赋值运算符要考虑"自赋值"的情况（自己给自己赋值）。
    // ========================================================================

    // 先加一个指针成员来演示深拷贝赋值
private:
    char* note;  // 备注（用char*指针，演示深拷贝）

public:
    // 设置备注
    void setNote(const char* n) {
        if (note) delete[] note;
        int len = strlen(n) + 1;
        note = new char[len];
        strcpy_s(note, len, n);
    }

    const char* getNote() const {
        return note ? note : "(无备注)";
    }

    // 赋值运算符重载（深拷贝版本）
    Complex& operator=(const Complex& other) {
        // 第一步：检查是不是自己给自己赋值
        if (this == &other) {
            return *this;  // 是就直接返回，不然释放了自己的内存就完蛋了
        }

        // 第二步：释放自己原来的资源
        if (note) {
            delete[] note;
            note = nullptr;
        }

        // 第三步：复制数据
        real = other.real;
        imag = other.imag;

        if (other.note) {
            int len = strlen(other.note) + 1;
            note = new char[len];
            strcpy_s(note, len, other.note);
        }

        // 第四步：返回 *this（支持链式赋值 a = b = c）
        return *this;
    }

    // 别忘了构造函数里要初始化 note
    // （上面的构造函数没加，这里补一下概念，实际例子里会处理）

    // ========================================================================
    // 六、自增自减运算符（++ --）
    // ========================================================================
    // 前置++ 和 后置++ 是两个不同的运算符！
    // 怎么区分？—— 后置的多一个 int 参数（没用，就是个占位符，让编译器区分）
    //
    // 前置 ++a：先加1，返回加完之后的值
    // 后置 a++：先返回原值，再加1
    // ========================================================================

    // 前置 ++ （++a）
    Complex& operator++() {
        real++;  // 这里简单地让实部+1，意思意思
        return *this;
    }

    // 后置 ++ （a++）
    // 注意那个 int 参数，没用，就是用来区分前置和后置的
    Complex operator++(int) {
        Complex temp = *this;  // 先保存原值
        real++;                // 再加1
        return temp;           // 返回原值
    }

    // 同理 -- 就不写了，套路一样

    // ========================================================================
    // 七、函数调用运算符 operator()
    // ========================================================================
    // 重载了 () 的对象，用起来像函数一样，所以叫"仿函数"。
    // 以后学 STL 的时候会大量用到。
    // ========================================================================

    // 比如：让复数对象像函数一样被调用，传入一个倍数，返回放大后的复数
    Complex operator()(double scale) const {
        return Complex(real * scale, imag * scale);
    }

    // ========================================================================
    // 八、类型转换运算符
    // ========================================================================
    // 可以把自定义类型转换成其他类型。
    // 语法：operator 目标类型() const { ... }
    // 注意：没有返回值（返回值类型就是目标类型）
    // ========================================================================

    // 把复数转换成 double（返回实部）
    explicit operator double() const {
        return real;
    }
    // 加了 explicit 关键字，表示必须显式转换，不能隐式转换
    // 这样更安全，防止编译器偷偷做一些你意想不到的转换
};

// ========================================================================
// 全局函数方式重载 * 和 /
// ========================================================================
// 为什么要用全局函数？比如 3 + c1，如果 operator+ 是成员函数，
// 左操作数必须是 Complex 类型，3 是 int 就不行。
// 用全局函数的话，两个参数都可以做隐式转换，更灵活。
// ========================================================================

Complex operator*(const Complex& a, const Complex& b) {
    // 复数乘法：(a+bi)*(c+di) = (ac-bd) + (ad+bc)i
    double r = a.real * b.real - a.imag * b.imag;
    double i = a.real * b.imag + a.imag * b.real;
    return Complex(r, i);
}

Complex operator/(const Complex& a, const Complex& b) {
    // 复数除法就不写太复杂了，简单意思一下
    double denom = b.real * b.real + b.imag * b.imag;
    if (denom == 0) return Complex(0, 0);
    double r = (a.real * b.real + a.imag * b.imag) / denom;
    double i = (a.imag * b.real - a.real * b.imag) / denom;
    return Complex(r, i);
}

// ============================================================================
// 九、友元函数与友元类
// ============================================================================
// 徒弟，友元就是"好朋友"的意思。
// 私有成员本来只有自己能访问，但如果把某个函数或类声明为友元，
// 那它也能访问你的私有成员了。
//
// 友元分两种：
//   1. 友元函数：某个函数是你的朋友
//   2. 友元类：整个类都是你的朋友
//
// 注意：友元关系是单向的，不传递的。
//   A 是 B 的朋友 ≠ B 是 A 的朋友
//   A 是 B 的朋友，B 是 C 的朋友 ≠ A 是 C 的朋友
//
// 什么时候用友元？—— 运算符重载用全局函数时，需要访问私有成员。
// 其他情况尽量少用，破坏封装性。
// ============================================================================

// --- 友元类的例子 ---
class GirlFriend;  // 前向声明（告诉编译器有这么个类）

class Boy {
private:
    int money;  // 小金库（私有的）
    string secret;  // 秘密

public:
    Boy(int m, string s) : money(m), secret(s) {}

    // 声明 GirlFriend 是我的朋友，她可以看我的小金库和秘密
    friend class GirlFriend;

    // 声明一个普通函数是友元
    friend void checkBoySecret(const Boy& boy);
};

// 友元函数
void checkBoySecret(const Boy& boy) {
    cout << "【友元函数】男生的小金库有：" << boy.money 
         << " 元，他的秘密是：" << boy.secret << endl;
}

class GirlFriend {
public:
    void checkBoy(const Boy& boy) {
        // 因为是友元类，所以能直接访问 private 成员
        cout << "【女朋友查岗】小金库：" << boy.money 
             << " 元，秘密：" << boy.secret << endl;
    }
};

// ============================================================================
// 主函数
// ============================================================================
int main() {
    cout << "==================== 09 - 运算符重载 ====================" << endl;
    cout << endl;

    // ---- 1. 算术运算符演示 ----
    cout << "--- 1. 算术运算符 + - * / ---" << endl;
    Complex c1(3, 4);    // 3 + 4i
    Complex c2(1, -2);   // 1 - 2i

    cout << "c1 = "; c1.print();
    cout << "c2 = "; c2.print();
    cout << endl;

    Complex c3 = c1 + c2;
    cout << "c1 + c2 = "; c3.print();

    Complex c4 = c1 - c2;
    cout << "c1 - c2 = "; c4.print();

    Complex c5 = c1 * c2;
    cout << "c1 * c2 = "; c5.print();

    Complex c6 = c1 / c2;
    cout << "c1 / c2 = "; c6.print();
    cout << endl;

    // ---- 2. 关系运算符演示 ----
    cout << "--- 2. 关系运算符 == != < > ---" << endl;
    Complex c7(3, 4);
    Complex c8(3, 4);
    Complex c9(5, 12);

    cout << "c7 和 c8 相等吗？" << (c7 == c8 ? "相等" : "不相等") << endl;
    cout << "c7 和 c9 相等吗？" << (c7 == c9 ? "相等" : "不相等") << endl;
    cout << "c7 < c9 吗？（比较模长平方）" << (c7 < c9 ? "是" : "否") << endl;
    cout << "c9 > c7 吗？" << (c9 > c7 ? "是" : "否") << endl;
    cout << endl;

    // ---- 3. 赋值运算符（深拷贝）演示 ----
    cout << "--- 3. 赋值运算符 = （深拷贝）---" << endl;
    Complex a(1, 2);
    a.setNote("这是第一个复数");
    cout << "a 的备注：" << a.getNote() << endl;

    Complex b(3, 4);
    b = a;  // 赋值运算符
    cout << "b = a 之后，b 的备注：" << b.getNote() << endl;

    // 修改 a 的备注，看看 b 会不会变
    a.setNote("我修改了备注");
    cout << "修改a后，a 的备注：" << a.getNote() << endl;
    cout << "修改a后，b 的备注：" << b.getNote()
         << "（没变，因为是深拷贝！）" << endl;
    cout << endl;

    // 自赋值测试
    a = a;
    cout << "a = a 自赋值后，a 的备注：" << a.getNote()
         << "（没崩，说明自赋值检查生效了）" << endl;
    cout << endl;

    // ---- 4. 自增运算符演示 ----
    cout << "--- 4. 自增运算符 ++（前置 vs 后置）---" << endl;
    Complex d(2, 3);
    cout << "初始 d = "; d.print();

    Complex e = ++d;  // 前置++：先加后用
    cout << "执行 e = ++d 后：" << endl;
    cout << "  d = "; d.print();
    cout << "  e = "; e.print();

    Complex f = d++;  // 后置++：先用后加
    cout << "执行 f = d++ 后：" << endl;
    cout << "  d = "; d.print();
    cout << "  f = "; f.print();
    cout << endl;

    // ---- 5. 函数调用运算符（仿函数）演示 ----
    cout << "--- 5. 函数调用运算符 () （仿函数）---" << endl;
    Complex g(2, 3);
    cout << "g = "; g.print();
    Complex h = g(3.0);  // 像函数一样调用对象
    cout << "g(3.0) = "; h.print();
    cout << "（把 g 放大了3倍）" << endl;
    cout << endl;

    // ---- 6. 类型转换运算符演示 ----
    cout << "--- 6. 类型转换运算符 ---" << endl;
    Complex i(5.5, 6.6);
    double r = static_cast<double>(i);  // 显式转换
    cout << "复数 i 的实部（转成double）：" << r << endl;
    // double r2 = i;  // 这行会报错，因为加了 explicit，不能隐式转换
    cout << endl;

    // ---- 7. 友元函数与友元类演示 ----
    cout << "--- 7. 友元函数与友元类 ---" << endl;
    Boy xiaoming(500, "我偷偷藏了私房钱");
    checkBoySecret(xiaoming);  // 友元函数

    GirlFriend xiaohong;
    xiaohong.checkBoy(xiaoming);  // 友元类
    cout << endl;

    cout << "=================== 程序结束 ===================" << endl;

    return 0;
}

