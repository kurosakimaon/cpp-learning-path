// ============================================================
// 01_basics.cpp - C++基础语法入门
// 编译命令：g++ -std=c++17 01_basics.cpp -o 01_basics
// ============================================================

#include <iostream>  // 输入输出流头文件，cin 和 cout 都在这里面
using namespace std; // 使用标准命名空间，后面会讲利弊

// ============================================================
// 一、第一个C++程序：Hello World
// ============================================================
// 老师傅说：main函数是程序的入口，就像工厂的大门，程序从这里开始运行
// int 表示函数返回一个整数，return 0 表示程序正常结束
int main()
{
    cout << "===== 1. Hello World =====" << endl;
    // cout 是控制台输出，<< 是插入运算符，把右边的东西"插"到输出流里
    // endl 是换行符，相当于 '\n'，但它还会刷新缓冲区
    cout << "Hello, World! 欢迎来到C++的世界！" << endl;
    cout << endl;

    // ============================================================
    // 二、变量与基本数据类型
    // ============================================================
    // 老师傅比喻：变量就像一个带标签的盒子，你可以往里面放东西，也可以取出来用
    // 数据类型决定了盒子的大小和能装什么东西
    cout << "===== 2. 变量与基本数据类型 =====" << endl;

    int age = 25;           // 整型：整数，本机占4字节（标准只要求 int 至少 16 位），范围约 -21亿 ~ 21亿
    float height = 1.75f;   // 单精度浮点型：小数，占4字节，精度约6-7位有效数字
    double pi = 3.1415926;  // 双精度浮点型：小数，占8字节，精度约15-16位有效数字
    char grade = 'A';       // 字符型：单个字符，占1字节，用单引号
    bool isStudent = true;  // 布尔型：真/假，占1字节，值为 true 或 false

    cout << "年龄（int）：" << age << endl;
    cout << "身高（float）：" << height << " 米" << endl;
    cout << "圆周率（double）：" << pi << endl;
    cout << "成绩等级（char）：" << grade << endl;
    cout << "是否是学生（bool）：" << (isStudent ? "是" : "否") << endl;
    // 小知识：bool值直接输出会显示 1 或 0，用三目运算符可以显示"是/否"

    // C++11 引入的 auto 自动类型推导（不是 C++17）
    auto score = 99.5;      // 编译器会自动推导出 score 是 double 类型
    cout << "auto推导的分数：" << score << "，类型是double" << endl;
    cout << endl;

    // ============================================================
    // 三、常量
    // ============================================================
    // 老师傅说：常量就是不能修改的量，就像刻在石头上的数字
    cout << "===== 3. 常量 =====" << endl;

    // 方式一：const 关键字（推荐！）
    const int MAX_AGE = 150;     // 人类最大年龄，常量用全大写命名是个好习惯
    // MAX_AGE = 200;  // 错误！const常量不能修改，编译器会报错

    // 方式二：#define 宏定义（C语言遗留，不推荐）
    #define PI 3.1415926535
    // 为什么不推荐#define？因为它没有类型检查，只是简单的文本替换，容易出bug

    cout << "const常量 MAX_AGE = " << MAX_AGE << endl;
    cout << "#define常量 PI = " << PI << endl;
    cout << "老师傅建议：尽量用 const，少用 #define" << endl;
    cout << endl;

    // ============================================================
    // 四、运算符
    // ============================================================
    cout << "===== 4. 运算符 =====" << endl;

    int a = 10, b = 3;

    // 4.1 算术运算符
    cout << "--- 算术运算符 ---" << endl;
    cout << "a = " << a << ", b = " << b << endl;
    cout << "a + b = " << (a + b) << endl;   // 加
    cout << "a - b = " << (a - b) << endl;   // 减
    cout << "a * b = " << (a * b) << endl;   // 乘
    cout << "a / b = " << (a / b) << endl;   // 除（注意：整数除法会截断小数）
    cout << "a % b = " << (a % b) << endl;   // 取余（模运算），只能用于整数

    // 自增自减运算符
    int x = 5;
    cout << "x = " << x << endl;
    cout << "x++ = " << x++ << "（后++，先用后加）" << endl;  // 先用x的值，再加1
    cout << "现在x = " << x << endl;
    cout << "++x = " << ++x << "（前++，先加后用）" << endl;  // 先加1，再用x的值
    cout << "现在x = " << x << endl;

    // 4.2 关系运算符（结果是bool值）
    cout << "--- 关系运算符 ---" << endl;
    cout << "a == b ？" << (a == b ? "相等" : "不相等") << endl;  // 等于
    cout << "a != b ？" << (a != b ? "不等" : "相等") << endl;    // 不等于
    cout << "a > b ？" << (a > b ? "大于" : "不大于") << endl;     // 大于
    cout << "a < b ？" << (a < b ? "小于" : "不小于") << endl;     // 小于
    cout << "a >= b ？" << (a >= b ? "大于等于" : "小于") << endl; // 大于等于
    cout << "a <= b ？" << (a <= b ? "小于等于" : "大于") << endl; // 小于等于

    // 4.3 逻辑运算符
    cout << "--- 逻辑运算符 ---" << endl;
    bool p = true, q = false;
    cout << "p = true, q = false" << endl;
    cout << "p && q（与）：" << (p && q ? "真" : "假") << endl;    // 并且，两边都真才真
    cout << "p || q（或）：" << (p || q ? "真" : "假") << endl;    // 或者，一边真就真
    cout << "!p（非）：" << (!p ? "真" : "假") << endl;            // 取反

    // 4.4 赋值运算符
    cout << "--- 赋值运算符 ---" << endl;
    int c = 10;
    c += 5;  // 等价于 c = c + 5;
    cout << "c += 5 后 c = " << c << endl;
    c -= 3;  // 等价于 c = c - 3;
    cout << "c -= 3 后 c = " << c << endl;
    c *= 2;  // 等价于 c = c * 2;
    cout << "c *= 2 后 c = " << c << endl;
    c /= 4;  // 等价于 c = c / 4;
    cout << "c /= 4 后 c = " << c << endl;

    // 4.5 位运算（简单了解，以后深入）
    cout << "--- 位运算符 ---" << endl;
    unsigned char m = 0b00001100;  // 二进制 12
    unsigned char n = 0b00001010;  // 二进制 10
    cout << "m = 12 (00001100), n = 10 (00001010)" << endl;
    cout << "m & n（按位与）：" << (int)(m & n) << " (00001000 = 8)" << endl;
    cout << "m | n（按位或）：" << (int)(m | n) << " (00001110 = 14)" << endl;
    cout << "m ^ n（按位异或）：" << (int)(m ^ n) << " (00000110 = 6)" << endl;
    cout << "m << 1（左移1位）：" << (int)(m << 1) << " (相当于乘2)" << endl;
    cout << "m >> 1（右移1位）：" << (int)(m >> 1) << " (相当于除以2)" << endl;
    cout << endl;

    // ============================================================
    // 五、流程控制
    // ============================================================
    cout << "===== 5. 流程控制 =====" << endl;

    // 5.1 if / else if / else
    cout << "--- if/else 分支 ---" << endl;
    int score2 = 85;
    cout << "分数：" << score2 << "，等级：";
    if (score2 >= 90) {
        cout << "优秀" << endl;
    } else if (score2 >= 80) {
        cout << "良好" << endl;
    } else if (score2 >= 60) {
        cout << "及格" << endl;
    } else {
        cout << "不及格" << endl;
    }

    // 5.2 switch 语句
    cout << "--- switch 分支 ---" << endl;
    char level = 'B';
    cout << "等级 " << level << " 对应的分数段：";
    switch (level) {
        case 'A': cout << "90-100分"; break;
        case 'B': cout << "80-89分"; break;
        case 'C': cout << "70-79分"; break;
        case 'D': cout << "60-69分"; break;
        default:  cout << "不及格";
    }
    cout << endl;
    // 老师傅提醒：每个case后面要加break，否则会"穿透"到下一个case

    // 5.3 for 循环
    cout << "--- for 循环：计算1到10的和 ---" << endl;
    int sum = 0;
    for (int i = 1; i <= 10; i++) {
        sum += i;
    }
    cout << "1+2+...+10 = " << sum << endl;

    // 5.4 while 循环
    cout << "--- while 循环：倒序数10到1 ---" << endl;
    int count = 10;
    while (count > 0) {
        cout << count << " ";
        count--;
    }
    cout << "发射！" << endl;

    // 5.5 do-while 循环（先执行，再判断，至少执行一次）
    cout << "--- do-while 循环 ---" << endl;
    int num = 0;
    do {
        cout << "num = " << num << "（至少执行一次）" << endl;
        num++;
    } while (num < 0);  // 条件不满足，但循环体还是执行了一次

    // 5.6 break 和 continue
    cout << "--- break 和 continue ---" << endl;
    cout << "1到10中的偶数（continue跳过奇数）：";
    for (int i = 1; i <= 10; i++) {
        if (i % 2 != 0) {
            continue;  // 跳过本次循环剩下的部分，进入下一轮
        }
        cout << i << " ";
    }
    cout << endl;

    cout << "遇到5就停止（break跳出循环）：";
    for (int i = 1; i <= 10; i++) {
        if (i == 5) {
            break;  // 直接跳出整个循环
        }
        cout << i << " ";
    }
    cout << endl;
    cout << endl;

    // ============================================================
    // 六、命名空间
    // ============================================================
    cout << "===== 6. 命名空间 =====" << endl;
    // 老师傅比喻：命名空间就像姓氏，两个"张伟"不会搞混，因为一个姓张一个姓李
    // std 是标准库的命名空间，cout、cin、endl 都住在 std 里面

    // 方式一：using namespace std;（文件开头已经写了）
    // 优点：写起来方便，不用每次都写 std::
    // 缺点：把std里的所有名字都引进来了，可能和自己写的名字冲突
    cout << "用了 using namespace std，直接写 cout 就行" << endl;

    // 方式二：using std::cout; using std::endl;（只引入需要的）
    // 这是更推荐的做法，既方便又不会引入太多名字

    // 方式三：每次都写 std::cout（最安全，大型项目推荐）
    // 最安全，但写起来麻烦一点

    cout << "老师傅建议：小项目/练习用 using namespace std 没问题" << endl;
    cout << "          大型项目最好用 std:: 前缀或只using需要的名字" << endl;
    cout << endl;

    // 输入用 std::cin（会等待键盘输入，所以这里只写注释，不实际执行）
    // int inputAge = 0;
    // cout << "请输入年龄：";
    // cin >> inputAge;              // 从键盘读一个整数
    // cout << "你输入的是：" << inputAge << endl;
    // 注意：cin 读取失败时要检查流状态，入门阶段先了解用法即可。
    cout << "输入用 cin，例如：int x; cin >> x;（本示例不阻塞等待输入）" << endl;
    cout << endl;

    // ============================================================
    // 老师傅的话
    // ============================================================
    cout << "========================================" << endl;
    cout << "  老师傅的话" << endl;
    cout << "========================================" << endl;
    cout << "  1. C++是强类型语言，变量必须先声明后使用" << endl;
    cout << "  2. 命名要有意义，别用 a、b、c 应付事儿" << endl;
    cout << "  3. 每一行代码背后都有它的道理，多问几个为什么" << endl;
    cout << "  4. 动手写代码才是王道，光看是学不会的" << endl;
    cout << "  5. 程序出bug很正常，调试能力也是程序员的基本功" << endl;
    cout << "========================================" << endl;
    cout << endl;

    // ============================================================
    // 小练习
    // ============================================================
    cout << "========================================" << endl;
    cout << "  小练习（动手写写看）" << endl;
    cout << "========================================" << endl;
    cout << "  1. 写一个程序，输入圆的半径，计算并输出面积和周长" << endl;
    cout << "  2. 用for循环输出九九乘法表" << endl;
    cout << "  3. 判断一个数是不是质数（素数）" << endl;
    cout << "  4. 输入一个三位数，输出它的个位、十位、百位分别是多少" << endl;
    cout << "  5. 用switch实现一个简单的计算器（+、-、*、/）" << endl;
    cout << "========================================" << endl;

    // return 0 表示程序正常结束
    // 非0值表示异常结束，操作系统能拿到这个返回值
    return 0;
}
