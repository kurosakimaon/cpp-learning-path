// ============================================================================
//  工具函数：生成测试数据
// ============================================================================
//  随机数组
vector<int> generateRandomArray(int n, int minVal = 1, int maxVal = 10000) {
    random_device rd;
    mt19937 gen(rd());
    uniform_int_distribution<> dis(minVal, maxVal);
    vector<int> arr(n);
    for (int i = 0; i < n; i++) arr[i] = dis(gen);
    return arr;
}

//  已排序数组（最好情况）
vector<int> generateSortedArray(int n) {
    vector<int> arr(n);
    for (int i = 0; i < n; i++) arr[i] = i + 1;
    return arr;
}

//  逆序数组（最坏情况）
vector<int> generateReversedArray(int n) {
    vector<int> arr(n);
    for (int i = 0; i < n; i++) arr[i] = n - i;
    return arr;
}

// ============================================================================
//  性能测试框架
