//  徒儿，这可是个好东西！咱们用它来公平地比比各个排序的本事。
using SortFunc = function<void(vector<int>&)>;

double measureTime(SortFunc sortFn, vector<int> arr) {
    auto start = chrono::high_resolution_clock::now();
    sortFn(arr);
    auto end = chrono::high_resolution_clock::now();
    chrono::duration<double, milli> duration = end - start;
    return duration.count();
}

// ============================================================================
//  【一】冒泡排序（Bubble Sort）
// ============================================================================
//
//  【算法思想】
//  徒儿，冒泡排序就像水里的气泡，大的数慢慢"冒"到最后面。
//  每一轮从头到尾比较相邻的两个数，如果前大后小就交换它们。
//  这样每轮结束，最大的数就被推到了末尾，像气泡浮出水面。
//
//  【稳定性】稳定的（相等的元素不会交换位置）
//  【时间复杂度】
//      - 最好：O(n)    （优化版，数组已经有序时）
//      - 最坏：O(n²)   （逆序时）
//      - 平均：O(n²)
//  【空间复杂度】O(1) （原地排序，只用到几个临时变量）
//
// ============================================================================

//  基础版冒泡排序
void bubbleSortBasic(vector<int>& arr) {
    int n = arr.size();
    //  外层循环：需要进行 n-1 轮
    //  每一轮都会把当前最大的数"冒"到最后
    for (int i = 0; i < n - 1; i++) {
        //  内层循环：从头比较到未排序部分的末尾
        //  注意是 n-1-i，因为后面 i 个已经排好了
        for (int j = 0; j < n - 1 - i; j++) {
            //  前大后小，交换！
            if (arr[j] > arr[j + 1]) {
                swap(arr[j], arr[j + 1]);
            }
        }
    }
}

//  优化版冒泡排序
//  徒儿，看这里！加个标志位，如果某轮没发生交换，说明已经有序了
void bubbleSortOptimized(vector<int>& arr) {
    int n = arr.size();
    for (int i = 0; i < n - 1; i++) {
        bool swapped = false;  //  本轮是否发生交换的标志
        for (int j = 0; j < n - 1 - i; j++) {
            if (arr[j] > arr[j + 1]) {
                swap(arr[j], arr[j + 1]);
                swapped = true;
            }
        }
        //  这一轮居然一个交换都没有？那说明已经全有序了！
        //  提前收工，省了不少功夫
        if (!swapped) break;
    }
}

// ============================================================================
//  【二】选择排序（Selection Sort）
// ============================================================================
//
//  【算法思想】
//  选择排序，顾名思义，就是每次"选择"最小的放到前面。
//  第一轮，从所有数里挑最小的，放第一个位置；
//  第二轮，从剩下的数里挑最小的，放第二个位置；
//  就这么一轮轮选下去，直到全部排完。
//
//  【稳定性】不稳定（比如 5 5 2，第一个5会和2交换，两个5的相对位置变了）
//  【时间复杂度】
//      - 最好：O(n²)
//      - 最坏：O(n²)
//      - 平均：O(n²)
//      （不管啥情况，都得老老实实找最小值，所以都是n²）
//  【空间复杂度】O(1)
//
// ============================================================================

void selectionSort(vector<int>& arr) {
    int n = arr.size();
    //  外层循环：当前要确定的位置
    for (int i = 0; i < n - 1; i++) {
        int minIdx = i;  //  先假设当前位置的数最小
        //  内层循环：在后面找真正最小的
        for (int j = i + 1; j < n; j++) {
            if (arr[j] < arr[minIdx]) {
                minIdx = j;  //  找到更小的，更新下标
            }
        }
        //  找到最小的了，把它换到第i个位置
        if (minIdx != i) {
            swap(arr[i], arr[minIdx]);
        }
    }
}

// ============================================================================
//  【三】插入排序（Insertion Sort）
// ============================================================================
//
//  【算法思想】
//  徒儿，插入排序就像你打扑克牌摸牌时一样：
//  手里的牌是排好序的，每摸到一张新牌，就插到合适的位置。
//  我们把数组分成"已排序"和"未排序"两部分，
//  每次从未排序部分拿第一个，插入到已排序部分的正确位置。
//
//  【稳定性】稳定的（相等的话不往前插，保持相对顺序）
//  【时间复杂度】
//      - 最好：O(n)    （数组已经有序，每个元素只需比较一次）
//      - 最坏：O(n²)   （逆序时，每个都要插到最前面）
//      - 平均：O(n²)
//  【空间复杂度】O(1)
//
//  老师傅悄悄告诉你：对于小规模或基本有序的数据，插入排序贼快！
//  很多高级排序算法（比如快排）在数据量小时会改用插入排序。
//
// ============================================================================

void insertionSort(vector<int>& arr) {
    int n = arr.size();
    //  从第二个元素开始，第一个元素默认已排序
    for (int i = 1; i < n; i++) {
        int key = arr[i];  //  这张牌要插入到前面
        int j = i - 1;
        //  从后往前找，比key大的都往后挪一位
        while (j >= 0 && arr[j] > key) {
            arr[j + 1] = arr[j];
            j--;
        }
        //  找到了位置，把key放进去
        arr[j + 1] = key;
    }
}

// ============================================================================
//  【四】希尔排序（Shell Sort）
// ============================================================================
//
//  【算法思想】
//  希尔排序是插入排序的"升级版"，也叫"缩小增量排序"。
//  徒儿你想啊，插入排序在数据基本有序时很快，但乱序时就慢了。
//  那希尔老先生就想了个招：先让数组"基本有序"，再用插入排序！
//
//  怎么个基本有序法？把数组按下标分成若干组，组内先做插入排序。
//  分组的间隔叫"增量"，增量逐渐缩小，直到增量为1（就是普通插入排序了）。
//  这样大的数能很快挪到后面，小的数能很快挪到前面。
//
//  【稳定性】不稳定（分组排序会打乱相等元素的相对顺序）
//  【时间复杂度】和增量序列的选择有关，大概在 O(n^1.3) ~ O(n²) 之间
//  【空间复杂度】O(1)
//
// ============================================================================

void shellSort(vector<int>& arr) {
    int n = arr.size();
    //  初始增量取数组长度的一半，然后每次减半
    //  这是希尔本人最初提出的增量序列，简单但不是最优的
    for (int gap = n / 2; gap > 0; gap /= 2) {
        //  对每个分组做插入排序
        //  注意这里i从gap开始，就像普通插入排序i从1开始一样
        for (int i = gap; i < n; i++) {
            int key = arr[i];
            int j = i;
            //  组内插入排序，步长是gap
            while (j >= gap && arr[j - gap] > key) {
                arr[j] = arr[j - gap];
                j -= gap;
            }
            arr[j] = key;
        }
    }
}

// ============================================================================
//  【五】归并排序（Merge Sort）
// ============================================================================
//
//  【算法思想】
//  归并排序是"分治法"（Divide and Conquer）的经典应用。
//  什么叫分治？就是"分而治之"——
//  把大问题拆成小问题，小问题解决了，再把结果合并起来。
//
//  具体到排序：
//  1. 分（Divide）：把数组从中间分成两半
//  2. 治（Conquer）：递归地给左右两半排序
//  3. 合（Merge）：把两个有序的子数组合并成一个有序数组
//
//  【稳定性】稳定的（合并时相等元素先取左边的，保持相对顺序）
//  【时间复杂度】
//      - 最好/最坏/平均：都是 O(n log n)
//      （每次分两半，分logn层；每层合并都是O(n)）
//  【空间复杂度】O(n) （合并时需要额外的临时数组）
//
//  老师傅说：归并排序虽然空间开销大一点，但它稳定啊！
//  而且它是链表排序的最佳选择，链表归并不需要额外空间。
//
// ============================================================================

//  合并两个有序区间：arr[left..mid] 和 arr[mid+1..right]
void merge(vector<int>& arr, int left, int mid, int right) {
    //  先把两个子数组拷出来，省得合并时覆盖了原数据
    vector<int> leftArr(arr.begin() + left, arr.begin() + mid + 1);
    vector<int> rightArr(arr.begin() + mid + 1, arr.begin() + right + 1);

    int i = 0;  //  左数组指针
    int j = 0;  //  右数组指针
    int k = left;  //  合并后数组的当前位置

    //  两个数组都还有元素，谁小取谁
    while (i < leftArr.size() && j < rightArr.size()) {
        if (leftArr[i] <= rightArr[j]) {
            arr[k++] = leftArr[i++];
        } else {
            arr[k++] = rightArr[j++];
        }
    }
    //  左边还有剩的，全倒进去
    while (i < leftArr.size()) arr[k++] = leftArr[i++];
    //  右边还有剩的，全倒进去
    while (j < rightArr.size()) arr[k++] = rightArr[j++];
}

//  归并排序的递归主体
void mergeSortHelper(vector<int>& arr, int left, int right) {
    //  递归终止条件：区间只有一个元素或空，自然有序
    if (left >= right) return;

    int mid = left + (right - left) / 2;  //  防止溢出的写法
    mergeSortHelper(arr, left, mid);       //  排左边
    mergeSortHelper(arr, mid + 1, right);  //  排右边
    merge(arr, left, mid, right);          //  合并
}

void mergeSort(vector<int>& arr) {
    mergeSortHelper(arr, 0, arr.size() - 1);
}

// ============================================================================
//  【六】快速排序（Quick Sort）
// ============================================================================
//
//  【算法思想】
//  快排也是分治法的代表，而且可以说是"最快"的通用排序算法了。
//  它的思路很巧妙：选一个"基准"（pivot），把数组分成三部分——
//  左边都比基准小，右边都比基准大，中间是基准自己。
//  这样基准就站到了它最终的位置上，然后左右两边再递归地排。
//
//  【三数取中优化】
//  徒儿，快排有个软肋：如果数组已经有序了，还每次选最左边当基准，
//  那每次分出来的就是一边0个一边n-1个，退化成了O(n²)。
//  怎么办呢？"三数取中"——从左、中、右三个位置选中间值当基准，
//  这样就能大大降低遇到最坏情况的概率。
//
//  【稳定性】不稳定（分区时的交换会打乱相等元素的相对顺序）
//  【时间复杂度】
//      - 最好/平均：O(n log n)
//      - 最坏：O(n²)   （但概率极低，加上三数取中基本不会遇到）
//  【空间复杂度】O(log n) ~ O(n) （递归调用栈的深度）
//
// ============================================================================

//  三数取中：返回左中右三个数中间值的下标
int medianOfThree(vector<int>& arr, int left, int right) {
    int mid = left + (right - left) / 2;
    //  让 arr[left] <= arr[mid] <= arr[right]
    if (arr[left] > arr[mid]) swap(arr[left], arr[mid]);
    if (arr[left] > arr[right]) swap(arr[left], arr[right]);
    if (arr[mid] > arr[right]) swap(arr[mid], arr[right]);
    //  现在 arr[mid] 是中间值，把它换到 right-1 的位置
    //  这样分区的时候只需要考虑 left+1 到 right-2
    swap(arr[mid], arr[right - 1]);
    return arr[right - 1];  //  返回基准值
}

//  分区函数：返回基准的最终位置
int partition(vector<int>& arr, int left, int right) {
    int pivot = medianOfThree(arr, left, right);  //  三数取中选基准
    int i = left;        //  左指针
    int j = right - 1;   //  右指针（因为基准在right-1）

    while (true) {
        //  从左往右找第一个 >= 基准的
        while (arr[++i] < pivot) {}
        //  从右往左找第一个 <= 基准的
        while (arr[--j] > pivot) {}
        if (i < j) {
            swap(arr[i], arr[j]);  //  交换
        } else {
            break;  //  指针相遇，分区完成
        }
    }
    //  把基准放到正确的位置（i的位置）
    swap(arr[i], arr[right - 1]);
    return i;
}

//  快速排序递归主体
void quickSortHelper(vector<int>& arr, int left, int right) {
    //  优化：小数组用插入排序，减少递归开销
    //  一般取 10~20 左右作为阈值，这里取 10
    if (right - left + 1 <= 10) {
        //  对小区间做插入排序
        for (int i = left + 1; i <= right; i++) {
            int key = arr[i];
            int j = i - 1;
            while (j >= left && arr[j] > key) {
                arr[j + 1] = arr[j];
                j--;
            }
            arr[j + 1] = key;
        }
        return;
    }

    int pivotPos = partition(arr, left, right);
    quickSortHelper(arr, left, pivotPos - 1);   //  排左边
    quickSortHelper(arr, pivotPos + 1, right);  //  排右边
}

void quickSort(vector<int>& arr) {
    quickSortHelper(arr, 0, arr.size() - 1);
}

// ============================================================================
//  【七】堆排序（Heap Sort）
// ============================================================================
//
//  【算法思想】
//  堆排序利用了"堆"这种数据结构（咱们后面数据结构那课会细讲）。
//  简单说，大顶堆就是个完全二叉树，父节点的值 >= 子节点的值。
//
//  堆排序的步骤：
//  1. 把数组构建成一个大顶堆（这样第一个元素就是最大值）
//  2. 把堆顶（最大值）和最后一个元素交换，相当于最大值排好了
//  3. 把剩下的元素重新调整成大顶堆
//  4. 重复步骤2-3，直到全部排好
//
//  【稳定性】不稳定
//  【时间复杂度】
//      - 最好/最坏/平均：都是 O(n log n)
//  【空间复杂度】O(1) （原地排序）
//
//  老师傅说：堆排序最大的优点是——不管啥数据都是O(n log n)，
//  而且是原地排序，空间开销小。适合内存紧张又要保证效率的场景。
//
// ============================================================================

//  调整堆：以 index 为根的子树，假设左右子树已经是堆
void heapify(vector<int>& arr, int n, int index) {
    int largest = index;          //  先假设根最大
    int left = 2 * index + 1;     //  左孩子
    int right = 2 * index + 2;    //  右孩子

    //  找三个里面最大的
    if (left < n && arr[left] > arr[largest]) largest = left;
    if (right < n && arr[right] > arr[largest]) largest = right;

    //  如果最大的不是根，就交换，然后继续往下调整
    if (largest != index) {
        swap(arr[index], arr[largest]);
        heapify(arr, n, largest);
    }
}

void heapSort(vector<int>& arr) {
    int n = arr.size();

    //  第一步：构建大顶堆
    //  从最后一个非叶子节点开始，从后往前调整
    //  最后一个非叶子节点的下标是 n/2 - 1
    for (int i = n / 2 - 1; i >= 0; i--) {
        heapify(arr, n, i);
    }

    //  第二步：一个个把堆顶元素"拿"到后面
    for (int i = n - 1; i > 0; i--) {
        swap(arr[0], arr[i]);    //  堆顶（最大）换到最后
        heapify(arr, i, 0);      //  剩下的 i 个元素重新调整成堆
    }
}

// ============================================================================
//  【八】计数排序（Counting Sort）
// ============================================================================
//
//  【算法思想】
//  计数排序是一种"非比较排序"，它不靠比较大小来排序。
//  思路很直接：先数一下每个数出现了多少次，然后按顺序输出就行了。
//
//  打个比方：你有一堆编号1~10的球，想给它们排序。
//  你就拿10个盒子编号1到10，把球扔进对应编号的盒子里，
//  最后按1到10的顺序从盒子里把球倒出来，就排好了！
//
//  【稳定性】可以做到稳定
//  【时间复杂度】O(n + k)，其中k是数据的范围（最大值-最小值+1）
//  【空间复杂度】O(k)
//
//  老师傅提醒：计数排序虽快，但有前提条件——
//  数据范围不能太大，而且最好是整数。
//  如果数据范围大、数量少，那空间就浪费大了。
//
// ============================================================================

void countingSort(vector<int>& arr) {
    if (arr.empty()) return;

    //  先找到最大值和最小值，确定范围
    int minVal = arr[0];
    int maxVal = arr[0];
    for (int num : arr) {
        if (num < minVal) minVal = num;
        if (num > maxVal) maxVal = num;
    }

    int range = maxVal - minVal + 1;  //  数据范围
    vector<int> count(range, 0);      //  计数数组

    //  第一步：统计每个数出现的次数
    for (int num : arr) {
        count[num - minVal]++;  //  减去minVal，让下标从0开始
    }

    //  第二步：按计数结果回填
    int index = 0;
    for (int i = 0; i < range; i++) {
        while (count[i] > 0) {
            arr[index++] = i + minVal;
            count[i]--;
        }
    }
}

