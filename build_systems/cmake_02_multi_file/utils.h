// ============================================================
//  utils.h - 工具函数头文件
// ============================================================
//  徒弟啊，头文件里放的是函数声明，告诉编译器"有这么个函数"，
//  具体实现在 .cpp 文件里。
//  为什么要分开？这是 C/C++ 的老传统了，好处有二：
//  1. 接口和实现分离，别人用你的库只需要看头文件
//  2. 加快编译速度，改实现不用重新编译所有引用它的文件
// ============================================================

//  这叫"头文件保护"，防止头文件被重复包含。
//  原理很简单：第一次包含时定义 UTILS_H，后面再包含时，
//  因为 UTILS_H 已经定义过了，里面的内容就被跳过了。
#ifndef UTILS_H
#define UTILS_H

#include <string>

// 打印一个漂亮的分隔线
void printSeparator();

// 打印带框的标题
void printTitle(const std::string& title);

// 获取当前时间的字符串表示
std::string getCurrentTimeString();

#endif // UTILS_H
